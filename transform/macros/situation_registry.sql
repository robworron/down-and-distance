{#
  The situation registry (seeds/situations.csv) as a list of rows, read from
  the database when a model or test runs. SQL generated by looping over it
  picks up a new situation as soon as it's added to the CSV: no SQL edits.

  dbt only records ref() calls it sees while parsing the project, and this
  query runs later, so every caller must declare the dependency itself with
  a comment line:  -- depends_on: {{ ref('situations') }}
  (and the same for any model referenced only inside a loop over it).
  That makes dbt load the seed before the caller runs.
#}
{% macro situation_registry() %}
    {% if execute %}
        {% set registry = run_query(
            "select key, level, column_name from " ~ ref('situations') ~ " order by key"
        ) %}
        {{ return(registry.rows) }}
    {% else %}
        {{ return([]) }}
    {% endif %}
{% endmacro %}
